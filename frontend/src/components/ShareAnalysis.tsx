import React, { useState } from 'react';
import { Share2, Copy, Download, Link, Check } from 'lucide-react';

interface ShareAnalysisProps {
  analysisData: {
    type: string;
    score: number;
    analysis: string;
    strengths: string[];
    weaknesses: string[];
  };
  summonerName: string;
  region: string;
}

const ShareAnalysis: React.FC<ShareAnalysisProps> = ({ analysisData, summonerName, region }) => {
  const [copied, setCopied] = useState(false);
  const [showShareMenu, setShowShareMenu] = useState(false);

  const generateShareableText = () => {
    const { type, score, strengths, weaknesses } = analysisData;
    
    return `🎮 League of Legends Analysis for ${summonerName} (${region.toUpperCase()})

📊 ${type} Score: ${score.toFixed(1)}/10

🟢 Top Strengths:
${strengths.slice(0, 3).map(s => `• ${s}`).join('\n')}

🔴 Areas for Improvement:
${weaknesses.slice(0, 3).map(w => `• ${w}`).join('\n')}

Generated by BlindSpot LOL`;
  };

  const copyToClipboard = async () => {
    try {
      await navigator.clipboard.writeText(generateShareableText());
      setCopied(true);
      setTimeout(() => setCopied(false), 2000);
    } catch (err) {
      console.error('Failed to copy:', err);
    }
  };

  const shareUrl = () => {
    const url = `${window.location.origin}?search=${encodeURIComponent(summonerName)}&region=${region}`;
    return url;
  };

  const copyUrl = async () => {
    try {
      await navigator.clipboard.writeText(shareUrl());
      setCopied(true);
      setTimeout(() => setCopied(false), 2000);
    } catch (err) {
      console.error('Failed to copy URL:', err);
    }
  };

  const downloadAsText = () => {
    const content = `BlindSpot LOL Report - ${summonerName} (${region.toUpperCase()})
Generated: ${new Date().toLocaleDateString()}

${analysisData.analysis}

STRENGTHS:
${analysisData.strengths.map((s, i) => `${i + 1}. ${s}`).join('\n')}

AREAS FOR IMPROVEMENT:
${analysisData.weaknesses.map((w, i) => `${i + 1}. ${w}`).join('\n')}

---
Generated by BlindSpot LOL`;

    const blob = new Blob([content], { type: 'text/plain' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `${summonerName}_${region}_analysis.txt`;
    document.body.appendChild(a);
    a.click();
    document.body.removeChild(a);
    URL.revokeObjectURL(url);
  };

  return (
    <div className="relative">
      <button
        onClick={() => setShowShareMenu(!showShareMenu)}
        className="flex items-center gap-2 px-4 py-2 bg-blue-600 hover:bg-blue-700 text-white rounded-lg transition-colors"
      >
        <Share2 className="w-4 h-4" />
        Share Analysis
      </button>

      {showShareMenu && (
        <div className="absolute top-full mt-2 right-0 bg-gray-800 border border-gray-700 rounded-lg shadow-xl z-50 min-w-48">
          <div className="p-2">
            <button
              onClick={copyToClipboard}
              className="w-full flex items-center gap-3 px-3 py-2 text-left hover:bg-gray-700 rounded transition-colors"
            >
              {copied ? <Check className="w-4 h-4 text-green-400" /> : <Copy className="w-4 h-4" />}
              <span className="text-sm">Copy Summary</span>
            </button>
            
            <button
              onClick={copyUrl}
              className="w-full flex items-center gap-3 px-3 py-2 text-left hover:bg-gray-700 rounded transition-colors"
            >
              <Link className="w-4 h-4" />
              <span className="text-sm">Copy Link</span>
            </button>
            
            <button
              onClick={downloadAsText}
              className="w-full flex items-center gap-3 px-3 py-2 text-left hover:bg-gray-700 rounded transition-colors"
            >
              <Download className="w-4 h-4" />
              <span className="text-sm">Download Report</span>
            </button>
          </div>
        </div>
      )}

      {copied && (
        <div className="absolute top-full mt-1 right-0 bg-green-600 text-white text-xs px-2 py-1 rounded">
          Copied!
        </div>
      )}
    </div>
  );
};

export default ShareAnalysis;
